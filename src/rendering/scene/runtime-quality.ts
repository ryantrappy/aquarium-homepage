/** Runtime LOD, lazy loading, and adaptive quality (AQ-76, tracker #18).
 *
 * Pure, renderer-independent policy: no WebGL, no DOM, no three.js imports,
 * so every rule below is unit-testable in the Node vitest environment.
 * `aquarium.ts` owns the wiring (GLB loads, fallback swaps, pixel-ratio and
 * shadow application); this module owns only the decisions.
 *
 * Calibration notes (measured on `gemini_control`, not invented):
 * - The camera sits at z = 9 with a 42-degree field of view and fish swim
 *   at z in -4.6..2.8, so camera-to-fish depth is only ~6.2 (nearest) to
 *   ~13.6 (farthest). Generic LOD distances (10/20/50) are meaningless
 *   here; the band below lives inside that 6-14 range.
 * - Projected fish length uses the same pixels-per-unit formula as
 *   `projectFishLinkBounds`: height / (2 * tan(fov/2) * depth). At 900 px
 *   height and 6.2 depth that is ~189 px per world unit, so a 1.44-unit
 *   blue-tang renders ~272 px long up close and a 0.36-unit tailspot-blenny
 *   ~24 px at far depth. The 140 px threshold follows from that.
 * - LOD1 keeps the full GLB and halves only the animation rate. No
 *   decimated `*_lod1.glb` assets are generated by this PR: decimating
 *   skinned GLBs risks breaking the skeleton/clip/turning-rig binding the
 *   scene depends on. If a future decimation spike proves safe, LOD1 can
 *   become a decimated asset without changing the threshold.
 * - The LOD2 thumbnail-sprite tier (far fish swapped to a flat 2D sprite
 *   billboard beyond ~11 m) was REMOVED 2026-11-09 at Ryan's direction:
 *   the swap read as a visible snap from a lifelike 3D fish to a flat
 *   model and was unrealistic. Fish now keep their full GLB at every
 *   depth; LOD is animation-rate only (LOD1 halves the clip cadence).
 *   The scene is ~133k triangles, so the extra far-fish geometry is
 *   small. The thumbnail sprite survives only as the no-GLB fallback
 *   (before a lazy load lands), never as a distance swap.
 * - Shadow toggle is NOT a no-op: reef meshes set `castShadow = true`
 *   (`reef-assembly.ts`, rock/coral assembly), so the Low tier's
 *   `keyLight.castShadow = false` genuinely skips the shadow pass.
 */

/** Fish depth (camera z minus fish z) below which a fish is LOD0. */
export const LOD_NEAR_DEPTH_M = 8.5
/** Depth hysteresis so a fish on the band boundary does not flicker tiers. */
export const LOD_DEPTH_HYSTERESIS_M = 0.75
/** Projected fish length at/above which a fish stays LOD0 regardless of depth. */
export const LOD_MIN_PROJECTED_PX = 140
/** Configured species whose GLBs block first paint (Phase 0). */
export const LAZY_PHASE0_MAX_SPECIES = 3
/** Background GLB loads in flight at once. */
export const LAZY_MAX_CONCURRENT_LOADS = 2
/** Maximum samples per adaptive-quality window; preserves the 120-frame path. */
export const ADAPTIVE_WINDOW_FRAMES = 120
/** Elapsed-time alternative for adaptive-quality evaluation windows. */
export const ADAPTIVE_WINDOW_DURATION_MS = 2000
/** Minimum valid samples before the elapsed-time window may be evaluated. */
export const ADAPTIVE_MIN_WINDOW_FRAMES = 30
/** Step down after sustained windows with EMA above this (ms). */
export const ADAPTIVE_STEP_DOWN_EMA_MS = 19
/** Step down after sustained windows with p95 above this (ms). */
export const ADAPTIVE_STEP_DOWN_P95_MS = 22
/** Step up after sustained windows with EMA below this (ms). */
export const ADAPTIVE_STEP_UP_EMA_MS = 13
/** Consecutive slow windows required to step down one tier. */
export const ADAPTIVE_STEP_DOWN_WINDOWS = 2
/** Consecutive fast windows required to step up one tier. */
export const ADAPTIVE_STEP_UP_WINDOWS = 3
/** Minimum time (ms) between tier changes, against oscillation. */
export const ADAPTIVE_COOLDOWN_MS = 5000
/** Low-tier tightening of the LOD depth band (fraction). */
export const ADAPTIVE_LOW_LOD_BIAS = 0.15

export type FishLod = 0 | 1
export type QualityTier = 'high' | 'balanced' | 'low'

/** Light-shaft rendering mode per quality tier (AQ-98 / AQ-86, tiered
 * by the same adaptive thresholds as everything else — see
 * `FRAME_TIME_BUDGET` in budgets.ts, which asserts the step-down
 * thresholds still equal the frame-time budget):
 * - `raymarch`: the depth-occluded screen-space raymarched shafts
 *   (High only — the most expensive light in the scene).
 * - `plane`: the upgraded wave-driven shaft plane (Balanced fallback).
 * - `reduced`: the same plane at half alpha (Low — shafts cost ~0). */
export type ShaftMode = 'raymarch' | 'plane' | 'reduced'

export const QUALITY_TIERS: Readonly<Record<QualityTier, { pixelRatioCap: number; shadows: boolean; lodBias: number; shafts: ShaftMode }>> = Object.freeze({
  high: { pixelRatioCap: 1.5, shadows: true, lodBias: 0, shafts: 'raymarch' },
  balanced: { pixelRatioCap: 1.0, shadows: true, lodBias: 0, shafts: 'plane' },
  low: { pixelRatioCap: 1.0, shadows: false, lodBias: ADAPTIVE_LOW_LOD_BIAS, shafts: 'reduced' },
})

/** Shaft rendering mode for a tier (the tier contract's shaft half). */
export function shaftModeForTier(tier: QualityTier): ShaftMode {
  return QUALITY_TIERS[tier].shafts
}

const DEG_TO_RAD = Math.PI / 180

/** Projected on-screen length (px) of a fish of `bodyLengthWorld` world
 * units at `depthM`, for a viewport `viewportHeightPx` tall and a camera
 * with `cameraFovDeg` vertical field of view. Mirrors the pixels-per-unit
 * formula in `projectFishLinkBounds`. Returns 0 for invalid depth. */
export function projectedFishLengthPx(bodyLengthWorld: number, viewportHeightPx: number, cameraFovDeg: number, depthM: number): number {
  if (!(depthM > 0) || !Number.isFinite(depthM) || !(bodyLengthWorld > 0) || !(viewportHeightPx > 0)) return 0
  return bodyLengthWorld * viewportHeightPx / (2 * Math.tan(cameraFovDeg / 2 * DEG_TO_RAD) * depthM)
}

/** Pick a fish LOD tier from camera depth and projected screen length.
 * The single depth band uses hysteresis against `previousLod` (a fish
 * steps down at band + 0.75 m and steps back up at band - 0.75 m);
 * projected length overrides depth (a large fish far away stays LOD0)
 * because screen size is what the viewer actually sees. `lodBias` (Low
 * tier) tightens the band. There is no far/sprite tier any more: the
 * LOD2 thumbnail-sprite swap was removed 2026-11-09 at Ryan's direction
 * (it read as a visible snap to a flat model), so a distant fish only
 * ever drops to LOD1 — full GLB, half clip rate — never to a sprite. */
export function selectFishLod(depthM: number, projectedLengthPx: number, previousLod: FishLod, lodBias = 0): FishLod {
  const near = LOD_NEAR_DEPTH_M * (1 - lodBias)
  let lod: FishLod
  if (previousLod === 0) lod = depthM > near + LOD_DEPTH_HYSTERESIS_M ? 1 : 0
  else lod = depthM < near - LOD_DEPTH_HYSTERESIS_M ? 0 : 1
  if (projectedLengthPx >= LOD_MIN_PROJECTED_PX) lod = 0
  return lod
}

/** Simulation steps between swim-clip advances for a LOD tier. LOD1
 * halves the clip cadence (every other step); there is no LOD2 any more,
 * so the clip never stops outright for distance. */
export function lodAnimationFrameSkip(lod: FishLod): number {
  return lod === 0 ? 1 : 2
}

/** Per-fish accumulator for animation updates sampled at the LOD cadence.
 * Call `consumeLodAnimationDelta` once for every active simulation step,
 * including steps where the renderer would otherwise skip clip/flex work.
 * LOD1 emits the sum of both fixed steps on every second call, preserving
 * animation time while halving update frequency. */
export interface LodAnimationDeltaState {
  pendingSeconds: number
  stepsSinceUpdate: number
  lod: FishLod
}

export function createLodAnimationDeltaState(initialLod: FishLod = 0): LodAnimationDeltaState {
  return { pendingSeconds: 0, stepsSinceUpdate: 0, lod: initialLod }
}

/** Accrue one fixed simulation delta and return elapsed animation seconds
 * only when the current LOD cadence is due. `paused` steps do not accrue
 * time; any partial active interval is retained and resumes deterministically.
 * A LOD change restarts the cadence count but keeps accrued active time, so
 * no time is lost and no paused-time catch-up is introduced. */
export function consumeLodAnimationDelta(
  state: LodAnimationDeltaState,
  simulationDeltaSeconds: number,
  lod: FishLod,
  paused = false,
): number {
  if (lod !== state.lod) {
    state.lod = lod
    state.stepsSinceUpdate = 0
  }

  if (paused) {
    state.stepsSinceUpdate = 0
    return 0
  }

  if (!(simulationDeltaSeconds > 0) || !Number.isFinite(simulationDeltaSeconds)) return 0

  state.pendingSeconds += simulationDeltaSeconds
  state.stepsSinceUpdate += 1
  if (state.stepsSinceUpdate < lodAnimationFrameSkip(lod)) return 0

  const elapsedSeconds = state.pendingSeconds
  state.pendingSeconds = 0
  state.stepsSinceUpdate = 0
  return elapsedSeconds
}

/** Configured species whose GLBs block first paint, in service order.
 * Everything else loads in the background after `ready`. */
export function phase0SpeciesIds(configuredFishIds: readonly string[]): string[] {
  return [...new Set(configuredFishIds)].slice(0, LAZY_PHASE0_MAX_SPECIES)
}

/** Order pending background GLB loads: the focused species first (if any),
 * then the remaining species in configured-service order. Unknown ids sort
 * last, in their original pending order. */
export function orderLazyLoadQueue(pendingFishIds: readonly string[], configuredFishIds: readonly string[], focusedFishId?: string): string[] {
  const order = new Map(configuredFishIds.map((id, index) => [id, index]))
  return [...new Set(pendingFishIds)].sort((a, b) => {
    if (focusedFishId !== undefined) {
      if (a === focusedFishId) return -1
      if (b === focusedFishId) return 1
    }
    return (order.get(a) ?? Number.MAX_SAFE_INTEGER) - (order.get(b) ?? Number.MAX_SAFE_INTEGER)
  })
}

/** Adaptive quality: frame-time EMA + p95 over ~2 s windows, with a tier
 * state machine that steps down on sustained slow frames and steps back up
 * on sustained headroom, with a cooldown against oscillation. Frames
 * recorded while hidden, paused, or under prefers-reduced-motion must never
 * be fed in — the caller excludes them — and excluded frames clear the
 * current window so a stale load signal cannot fire after a resume. */
export class AdaptiveQualityController {
  private tier: QualityTier = 'high'
  private emaMs: number | undefined
  private samples: number[] = []
  private windowStartedAtMs: number | undefined
  private slowWindows = 0
  private fastWindows = 0
  private lastChangeAtMs = -Infinity

  constructor(initialTier: QualityTier = 'high') {
    this.tier = initialTier
  }

  get currentTier(): QualityTier {
    return this.tier
  }

  /** Feed one rAF frame interval (ms) at monotonic timestamp `nowMs`.
   * Pass `excluded: true` for hidden/paused/reduced-motion frames: they
   * are dropped and the in-progress window is discarded. */
  recordFrameInterval(intervalMs: number, nowMs: number, excluded = false): void {
    if (excluded) {
      this.samples = []
      this.emaMs = undefined
      this.windowStartedAtMs = undefined
      this.slowWindows = 0
      this.fastWindows = 0
      return
    }
    if (!(intervalMs > 0) || !Number.isFinite(intervalMs) || !Number.isFinite(nowMs)) return
    if (this.windowStartedAtMs === undefined) this.windowStartedAtMs = nowMs
    this.emaMs = this.emaMs === undefined ? intervalMs : this.emaMs * 0.9 + intervalMs * 0.1
    this.samples.push(intervalMs)
    if (this.samples.length > ADAPTIVE_WINDOW_FRAMES) this.samples.shift()
  }

  /** Evaluate the current window once it holds 120 samples, or at least 30
   * samples spanning 2 seconds, and return the tier active at `nowMs`. No tier change
   * is made before a full window, during cooldown, or on a single slow
   * window — stepping down needs 2 consecutive slow windows, stepping up
   * needs 3 consecutive fast windows. */
  evaluate(nowMs: number): QualityTier {
    const fullSampleWindow = this.samples.length >= ADAPTIVE_WINDOW_FRAMES
    const elapsedWindow = this.samples.length >= ADAPTIVE_MIN_WINDOW_FRAMES
      && this.windowStartedAtMs !== undefined
      && nowMs - this.windowStartedAtMs >= ADAPTIVE_WINDOW_DURATION_MS
    if ((!fullSampleWindow && !elapsedWindow) || this.emaMs === undefined) return this.tier
    const sorted = [...this.samples].sort((a, b) => a - b)
    const p95 = sorted[Math.min(sorted.length - 1, Math.floor(0.95 * sorted.length))]
    const ema = this.emaMs
    this.samples = []
    this.windowStartedAtMs = undefined
    const cooledDown = nowMs - this.lastChangeAtMs >= ADAPTIVE_COOLDOWN_MS
    if (ema > ADAPTIVE_STEP_DOWN_EMA_MS || p95 > ADAPTIVE_STEP_DOWN_P95_MS) {
      this.slowWindows++
      this.fastWindows = 0
      if (this.slowWindows >= ADAPTIVE_STEP_DOWN_WINDOWS && cooledDown) {
        this.tier = this.tier === 'high' ? 'balanced' : 'low'
        this.slowWindows = 0
        this.lastChangeAtMs = nowMs
      }
    } else if (ema < ADAPTIVE_STEP_UP_EMA_MS) {
      this.fastWindows++
      this.slowWindows = 0
      if (this.fastWindows >= ADAPTIVE_STEP_UP_WINDOWS && cooledDown) {
        this.tier = this.tier === 'low' ? 'balanced' : 'high'
        this.fastWindows = 0
        this.lastChangeAtMs = nowMs
      }
    } else {
      this.slowWindows = 0
      this.fastWindows = 0
    }
    return this.tier
  }
}
